// Helper for scripts/deploy.sh (no dependencies, never prints secret values).
//   node scripts/deploy-helper.mjs config-get <key>                 -> prints name | database_name from wrangler.jsonc
//   node scripts/deploy-helper.mjs d1-id <name> < d1-list.json      -> prints the uuid of the database called <name>
//   node scripts/deploy-helper.mjs write-config <worker> <db> <id>  -> writes wrangler.deploy.jsonc (git-ignored)
//   node scripts/deploy-helper.mjs secrets <existing.json> <out.json> -> decides which secrets to upload (see below)
import fs from 'node:fs';
import { randomBytes } from 'node:crypto';

const [cmd, ...args] = process.argv.slice(2);
const readStdin = () => fs.readFileSync(0, 'utf8');

/** wrangler.jsonc -> object. Only full-line // comments are used in that file (and trailing commas are tolerated). */
function readBaseConfig() {
  const text = fs.readFileSync('wrangler.jsonc', 'utf8')
    .split('\n').filter((l) => !/^\s*\/\//.test(l)).join('\n')
    .replace(/,(\s*[}\]])/g, '$1');
  return JSON.parse(text);
}

if (cmd === 'config-get') {
  const c = readBaseConfig();
  const v = args[0] === 'database_name' ? c.d1_databases[0].database_name : c[args[0]];
  process.stdout.write(String(v ?? ''));
} else if (cmd === 'd1-id') {
  let list = [];
  try { list = JSON.parse(readStdin()); } catch { /* empty */ }
  const d = (Array.isArray(list) ? list : list.result ?? []).find((x) => x.name === args[0]);
  process.stdout.write(d ? d.uuid ?? d.id ?? '' : '');
} else if (cmd === 'write-config') {
  const [worker, db, id] = args;
  if (!/^[a-z0-9][a-z0-9-]{0,62}$/.test(worker)) throw new Error(`invalid worker name "${worker}" (lowercase letters, digits, dashes)`);
  if (!/^[0-9a-f-]{36}$/.test(id)) throw new Error('invalid D1 database id');
  const c = readBaseConfig();
  c.name = worker;
  c.d1_databases[0].database_name = db;
  c.d1_databases[0].database_id = id;
  fs.writeFileSync('wrangler.deploy.jsonc', '// GENERATED by scripts/deploy.sh from wrangler.jsonc — do not edit, do not commit.\n' + JSON.stringify(c, null, 2) + '\n');
} else if (cmd === 'secrets') {
  // Inputs: existing secret names (wrangler secret list JSON), env SETUP_TOKEN / ADMIN_PASSWORD_HASH (optional),
  //         env HAS_DB_PASSWORD=1 when D1 already holds an admin password, env INTERACTIVE_LOCAL=1 outside CI on a TTY.
  // Rules: ENCRYPTION_KEY / SESSION_SECRET are set only when absent on the Worker (never overwritten): taken from the
  //        environment when given (e.g. a passphrase), otherwise generated randomly.
  //        SETUP_TOKEN / ADMIN_PASSWORD_HASH from the environment are uploaded as given.
  //        With no admin password and no setup token anywhere: locally a token is generated and written to
  //        ./SETUP_TOKEN.txt (mode 600); in CI nothing is generated (the dashboard explains what to do).
  const [existingFile, out] = args;
  let existing = [];
  try { existing = JSON.parse(fs.readFileSync(existingFile, 'utf8')).map((s) => s.name); } catch { /* new worker */ }
  const s = {};
  const notes = [];
  const gen = { ENCRYPTION_KEY: () => randomBytes(32).toString('base64'), SESSION_SECRET: () => randomBytes(48).toString('base64url') };
  for (const name of ['ENCRYPTION_KEY', 'SESSION_SECRET']) {
    const given = (process.env[name] ?? '').trim();
    if (existing.includes(name)) { if (given) notes.push(`${name} already set on the Worker — kept (never overwritten)`); continue; }
    if (given) {
      if (given.length < 32 || new Set(given).size < 6) { console.error(`ERROR: ${name} must be at least 32 characters (a long passphrase is fine)`); process.exit(2); }
      s[name] = given; notes.push(`${name} from environment`);
    } else { s[name] = gen[name](); notes.push(`${name} generated`); }
  }
  const envTok = (process.env.SETUP_TOKEN ?? '').trim();
  if (envTok) {
    if (envTok.length < 12) { console.error('ERROR: SETUP_TOKEN must be at least 12 characters'); process.exit(2); }
    s.SETUP_TOKEN = envTok; notes.push('SETUP_TOKEN from environment');
  }
  const envHash = (process.env.ADMIN_PASSWORD_HASH ?? '').trim();
  if (envHash) {
    if (!/^pbkdf2\$sha256\$\d+\$[^$]+\$[^$]+$/.test(envHash)) { console.error('ERROR: ADMIN_PASSWORD_HASH must come from `npm run hash-password`'); process.exit(2); }
    s.ADMIN_PASSWORD_HASH = envHash; notes.push('ADMIN_PASSWORD_HASH from environment');
  }
  const hasPassword = existing.includes('ADMIN_PASSWORD_HASH') || !!envHash || process.env.HAS_DB_PASSWORD === '1';
  const hasToken = existing.includes('SETUP_TOKEN') || !!envTok;
  if (!hasPassword && !hasToken) {
    if (process.env.INTERACTIVE_LOCAL === '1') {
      const tok = randomBytes(18).toString('base64url');
      s.SETUP_TOKEN = tok;
      fs.writeFileSync('SETUP_TOKEN.txt', `Setup token for the first dashboard visit (create the admin password, then delete this file):\n${tok}\n`, { mode: 0o600 });
      notes.push('SETUP_TOKEN generated -> ./SETUP_TOKEN.txt (mode 600)');
    } else {
      notes.push('NOTE: no admin password and no SETUP_TOKEN — set the SETUP_TOKEN secret (repo secret or `wrangler secret put SETUP_TOKEN`), then open the dashboard');
    }
  }
  fs.writeFileSync(out, JSON.stringify(s), { mode: 0o600 });
  console.error('    ' + (notes.length ? notes.join('\n    ') : 'all secrets already set'));
} else {
  console.error('unknown command'); process.exit(1);
}
